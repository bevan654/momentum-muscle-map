/** The subject's left or right, not the viewer's. */
export type Side = 'left' | 'right';

/** How finely the body is divided when drawn. */
export type Level = 'groups' | 'muscles' | 'parts';

/** One drawable region of a body at one level. */
export interface BodyUnit {
  /** Unique within its level: the slug followed by `_left` or `_right`. */
  id: string;
  side: Side;
  /** Indexes into `BodyData.paths`. The region is the union of these sub-paths. */
  paths: number[];
  /** A point well inside the region, for labels. */
  c: [x: number, y: number];
  /** Bounding box as [minX, minY, maxX, maxY]. */
  bb: [minX: number, minY: number, maxX: number, maxY: number];
}

/** One view of one body (for example male, front). Generated by the pipeline. */
export interface BodyData {
  viewBox: [x: number, y: number, width: number, height: number];
  /** Bounding box of the silhouette as [minX, minY, maxX, maxY]. */
  bounds: [minX: number, minY: number, maxX: number, maxY: number];
  /** The silhouette as an SVG path. */
  outline: string;
  /** Pool of SVG sub-paths shared by every level. */
  paths: string[];
  /** Units are listed in draw order, back to front. */
  parts: BodyUnit[];
  muscles: BodyUnit[];
  groups: BodyUnit[];
}

/**
 * Intensities from 0 to 1, keyed by a group, muscle or part slug, with or
 * without a `_left` / `_right` suffix. See `resolveValues` for how keys at
 * different levels combine.
 */
export type MuscleValues = Readonly<Record<string, number | undefined>>;

/** What a unit is, in terms of the hierarchy. */
export interface RegionInfo {
  id: string;
  /** The id without its side suffix. */
  key: string;
  side: Side;
  level: Level;
  /** The muscle this unit is or belongs to. Absent for a group. */
  muscle?: string;
  group: string;
  /** False for tendons, fascia and the kneecap, which never take a value. */
  isMuscle: boolean;
}
